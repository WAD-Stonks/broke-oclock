import type { DealApplicability, OfferType, ReviewStatus } from '@db/generated/prisma/index'

// Synthetic promotions for local development. Every record is labelled as seed data at build time.
export type SeedCategory = 'FOOD' | 'DRINKS' | 'DESSERT' | 'SNACKS' | 'BAKERY'

// Validity is relative to the seeding time, in days, so "current" deals stay current on rerun.
export type SeedValidity =
  | { readonly kind: 'window'; readonly fromDays: number; readonly untilDays: number }
  | { readonly kind: 'open'; readonly fromDays: number; readonly rawText: string }

export type SeedDeal = {
  readonly key: string
  readonly title: string
  readonly description: string
  readonly category: SeedCategory
  readonly offerType: OfferType
  readonly terms?: string
  readonly priceMinor?: number
  readonly discountPercent?: number
  readonly validity: SeedValidity
  readonly applicability: DealApplicability
  readonly merchant?: string
  readonly venues?: readonly string[]
  readonly review: ReviewStatus
  readonly reviewNote?: string
}

const window = (fromDays: number, untilDays: number): SeedValidity => ({
  kind: 'window',
  fromDays,
  untilDays,
})
const open = (fromDays: number, rawText: string): SeedValidity => ({
  kind: 'open',
  fromDays,
  rawText,
})

const fixed = (priceMinor: number) => ({ offerType: 'FIXED_PRICE' as const, priceMinor })
const percent = (discountPercent: number) => ({
  offerType: 'PERCENT_OFF' as const,
  discountPercent,
})
const bogo = { offerType: 'BUY_ONE_GET_ONE' as const }
const other = { offerType: 'OTHER' as const }

const at = (merchant: string, ...venues: string[]) => ({
  applicability: 'SELECTED_OUTLETS' as const,
  merchant,
  venues,
})
const everyOutlet = (merchant: string) => ({
  applicability: 'ALL_MERCHANT_OUTLETS' as const,
  merchant,
})
const online = (merchant: string) => ({ applicability: 'ONLINE' as const, merchant })
const noFixedLocation = (merchant?: string) => ({
  applicability: 'NO_FIXED_LOCATION' as const,
  merchant,
})

